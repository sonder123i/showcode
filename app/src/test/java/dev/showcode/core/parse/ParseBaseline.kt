package dev.showcode.core.parse

/**
 * 解析棘轮的地板。五个数字来自 `dev.showcode.core.parse.corpus.ALL` 的全量跑分，
 * 完整漏项清单在 `app/build/parse-metrics.txt`（每次跑分重写）。
 *
 * 抬它只有一个动作：改解析器 → 重跑 `ParseMetricsTest` → 把新数字填回来，
 * 并在 commit 里写清楚这次治好了哪几条语料。**语料集不变时不许下调地板**——
 * 那等于把已知丢件重新藏起来。语料集变了怎么算，见下面「地板规则」。
 *
 * 口径（第八轮后）：语料 42 条 = 20 条应进门 + 20 条不该进门 + 2 条不进分母
 * （1 条真值存疑、1 条真值无争议但解析器还治不好，见下面的占位说明）。
 * 其中 2 条（`adv-*`）是我为攻自己写的规则而造的对抗题，不是真短信——它们只当守门用例用。
 * 来源上：13 条是 `shareven/parcel` issue 里真人报过的原文（脱敏轮换后），另 2 条是用户真机短信。
 * 所以这一批不是「我猜的难点」，是「已经有人因此白跑过的写法」。
 *
 * ⚠️ 用户自定义解析规则（`ParseRule` / `ParseRules`）**不进这五个数字**，也不许往里加语料。
 * 它只在内置一个码都没认出来时才补位，而 [ParseMetrics.measure] 连传规则的入口都没有——
 * 所以这一层既抬不高地板（它治好的写法不在分母里），也压不低地板（它碰不到内置已经认出的件）。
 * 它治好的是「某一个人手机上的第 43 条写法」。把那条写法收进公共语料是个看似自然的收尾动作，
 * 真做了就等于承认我们在靠枚举追赶无限文案——那一件事这一层存在的理由恰恰是不再干。
 *
 * 2026-10-12 第一轮抬地板：换行不再进点名、认「N号柜」与汉字柜号、认「下午/晚上 N 点前」、
 * 免费时长两种词序都认 → 字段准确率 78％ 升到 90％。
 * 进门率、无痕蒸发率、误收率**一个都没动**，因为这一轮刻意不碰「进门」：
 * 那一步是拿误收换召回，得先把负向锚想清楚。
 *
 * 2026-10-12 第二轮（进门重构，见 `MessageGate`）：进门改成「强锚定 → 负向锚 → 语境 → 弱锚定」的分级判定，
 * 两张表不再互相当闸门 → 进门率 72％ 升到 100％、**无痕蒸发 11％ 降到 0％**、误收 20％ 降到 0％，
 * 字段准确率 90→91％（分母 50→62：新进门的 6 条开始被逐字段考核）。
 *
 * 2026-10-12 第三轮（一条多件切分）：`ParseOutcome.Parsed` 从单件改成 `parcels` 列表，
 * 「取件码 7-1-3392、7-2-8801」和锚定词各写一次这两种真实写法都能切出两件；
 * 同时上两道精度闸门并各有语料守着——**同形**（纯数码后面跟着的 A12 是格口不是件）、
 * **量词**（「，24小时内免费」里的 24 是保管时长不是件）。字段准确率 91→94％。
 * 多件时柜号一律不填（一条短信只有一个格口却对应两件，猜给谁都是赌）。
 *
 * 2026-10-12 第四轮（不确定点名走确认）：认不出具体门店时不再退化成「菜鸟驿站」「丰巢快递柜」
 * 直接成卡（那会把不同小区合成一张，用户站在 A 点看着 B 点的码且毫不怀疑），
 * 改成 REJECTED(POINT_NAME_UNCONFIRMED) 并把认出来的码一起带下去（`Rejected.codes`），
 * 用户在手动导入页只补一个名称。代价单独做成第五个指标「需确认率」——
 * 因为这一改进门率和字段准确率会**自己变好看**，只有需确认率看得见真实代价。
 *
 * 2026-10-12 第五轮（点名信息的两端）：拼多多/兔喜那种「品牌 代收点 | 门店名」的分段粘贴文本
 * 现在能抽出竖线后面的真门店名；同时把判据从「名字是从哪抽出来的」升级成
 * 「名字本身含不含具体门店信息」——「丰巢柜」「京东自提点」即使抽自动词短语也是通用名。
 * 语料 34 → 35 条，按上面的规则重新实测地板：**需确认率 36→30％**（7/23）。
 * 剩下的 7 条是天花板：那些消息里根本没有门店信息，再聪明的正则也变不出来。
 * 要再降只能换机制——「确认一次就记住」（本地别名映射），不是继续调正则。
 *
 * 2026-10-13 第六轮（点名换机制：类别词向前回吃）：`POINT_NAME` 那 12 个到达类动词是**开集**，
 * 补不完；改成定位**闭集**类别词（驿站/代收点/自提点/超市/便利店/门店/快递柜…）再向前回吃到边界，
 * 一条规则同时覆盖「到X取」「已在X滞留」「已到达X」「请前往X领取」。
 * 语料 35 → 37 条（两条用户真机样本），按地板规则重新实测：**需确认率 30→28％**（7/24），
 * 进门率 16→17 条仍 100％，字段 65/66 → 70/71 仍 98％，无痕蒸发与误收保持 0。
 *
 * 两件不体面但必须记下的事：
 * 1. **这条规则在旧 35 条上收益恰好为零**——需确认率仍是 7/23，那 7 条是真的不含门店信息。
 *    它只治好新进来的极兔那条。这就是上面「100％ 只证明已知写法都能处理」的实证：
 *    没有真机语料进来，任何机制改进都测不出差别。
 * 2. **第一版只卡了名字的左边界，被语料当场抓出两条误收**（0％ → 11％）：
 *    「…咨询**驿站**工作人员」抽成「咨询驿站」，「【示例驿站】」抽成「示例驿站」。
 *    修法是两头都卡：类别词后面必须落在标点/动词/句尾，且右括号右引号**故意不算边界**
 *    （以右括号收尾说明整段是被包起来的签名或占位符），左边再加一个挡左括号的负向前后查找。
 *    单字「柜」也不收：「到9号柜取件」里的「9号柜」是格口，收了就造假卡——这条有 up-56 守着。
 *
 * 2026-10-13 第七轮（闭集补「品牌+柜」，并从竞品 issue 区再采三条真原文）：
 * 语料 37 → 40 条（issue #16 / #18 / #48 的真人原文，脱敏后），进门率 17→19 仍 100％，
 * 字段 70/71 → 80/81 仍 98％，需确认率 7/24 → 8/27 仍 28％，无痕蒸发与误收保持 0。
 * 闭集补「丰巢柜 / 智慧柜 / 菜鸟柜」（#16「至火星1号丰巢柜取件」），
 * 但**明确不收「服务中心」**——#18 那条正文里没有任何门店标识，收了就是替用户猜点数。
 *
 * ⚠️ 这一轮棘轮抓到一个我自己写出来的真 bug，值得留着当教训：
 * 回吃正则写成 `[^边界]*[0-9A-Za-z一-龥]类别词`，边界只挡在可空前缀上，
 * **紧邻类别词的那个必填字符没挡**，于是「快件已放**入**丰巢柜」照样抽出「入丰巢柜」——
 * 它躲过了 GENERIC_NAME（那个判据只认「品牌+类别词」的干净形状），误收率当场 0 → 5％。
 * 修法是前缀与必填字符合成同一个 `NAME_CHAR{1,}`。第一次只补「入」字进边界表是不够的。
 *
 * 产品判断一条（#48）：「已到 + 一整段相对位置」（邮局斜对面示例大酒店隔壁）**判可用**，
 * 不判脏。理由：措辞变化最多把同一个点分裂成两张卡，而首页的合并（预览 + 5 秒撤销 +
 * 别名登记）正是为这件事准备的；判脏会让件掉进未识别列表、用户根本不会发现，
 * 那是无痕蒸发。**可恢复的错误不该换成不可恢复的错误。**
 *
 * 2026-10-13 第八轮（对抗自测，不是补规则）：我自己造 14 条题去攻第六、七轮那套闭集回吃。
 * **造题只能用来攻，不能用来夸**——自己造的题必然落在已经想到的形态里，所以这一轮只统计
 * 「被打穿了几条」。结果 8 条守住、3 类被打穿，其中两个当场修掉，语料 40 → 42 条：
 * - `adv-two-points`（灾难类）：一条消息里两个点，`extractPointName` 只返回一个名字，
 *   于是第二件被**静默挂到第一个点上**——用户站在 A 点看着 B 点的码且毫不怀疑。
 *   修法和「唯一幸存者」同构：**出现两个不同点位短语就放弃定名**。
 *   ⚠️ 这条判据必须给竖线格式留一格：`品牌 代收点 | 门店名` 天然含两个类别词，
 *   那是同一个点写了两遍。第一版没留，进门率当场 100→94％（up-29-a 被打回未识别）。
 * - `adv-address-shop`：边界表收了单字「放」，于是「**解放路**12号…」被从地名中间切成「路12号…」。
 *   结构性教训：**单字边界天然会切进中文地名**（解放路、到达厅、育才路），而地名正是门店名的主要成分。
 *   修法是把边界拆成两张表——前向只留不可能出现在店名里的虚词，尾边界单独一张放宽；
 *   动词一律降到**词组**层剥离（放入/投放/已到达/送到…），剥完再交给 GENERIC_NAME 判通用名。
 * - 第三个洞**没修**：连锁品牌冒充门店（「妈妈驿站」「联华超市」没有任何门店标识却成卡，
 *   不同门店会合成一张）。末端品牌是开集，`GENERIC_NAME` 那 10 个快递品牌覆盖不到，
 *   而我给不出不靠枚举的干净判据——**这条等真样本校准，不硬做**。
 *
 * 代价按地板规则重新实测：需确认率 28 → **31％**（9/29）。这一项上升是补上多点判据的
 * **预期结果**，不是退化：那一类消息从「看着可信的错卡」变成了「等人确认」。
 *
 * ⚠️ 地板规则（我先前写得太宽，这里修正）：「只许升」只适用于**语料集不变**的时候。
 * 语料集一变（比如下一批加真机语料），分母就变了，地板必须重新实测——那种下降不是回归。
 * 判据只有一条：commit 里必须写清这次动的是解析器还是语料。
 *
 * ⚠️ 两个 100％ 都不该读成质量到顶：进门率的分母是 20 条我们已经会的形态，
 * 最难的 9 条被显式改判成「等人确认」，它们只考核一件事——码有没有被带走。
 * 真正要盯的是需确认率和待确认清单。而 100％ 本身也只证明「语料里已知写法全都能处理」，
 * 不证明「中国没有我不知道的写法」：下一个未知漏件只能靠真机语料或未识别列表回流才能发现。
 */
object ParseBaseline {

    /** 该收的里面真收进来多少（越高越好）。20/20。 */
    const val GATE_RECALL = 1.0

    /** 收进来之后各字段抽对多少（越高越好）。84/85——唯一那条漏的是竖线左半截里的类型。 */
    const val FIELD_ACCURACY = 0.98

    /**
     * 需确认率（越低越好）。9/29——认出码但说不出在哪个点，这一项才是真实代价。
     *
     * ⚠️ 28→31％ 是**买来的**，不是退步：第八轮补上「一条消息里两个不同点位短语就放弃定名」之后，
     * `adv-two-points` 那一类从「一张看着可信、实际把第二件静默挂到第一个点上的错卡」变成了「待确认」。
     * 这一项上升正是那条改动的**预期代价**，把它压回 28％ 的唯一办法是把灾难重新藏回卡片区。
     */
    const val UNCONFIRMED_RATE = 0.31

    /** 应进却整条无痕蒸发的比例（越低越好）。0/20。 */
    const val SILENT_LOSS = 0.0

    /** 不该进来的变成假快递或角标噪音的比例（越低越好）。0/20。 */
    const val FALSE_INTAKE = 0.0
}
