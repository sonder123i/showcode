package dev.showcode.core.parse

/**
 * 「这条消息是不是喊我去取件」的判据。
 *
 * 原来它是一道纯关键词闸门（`PICKUP_SIGNAL`），而抽码用的是另外一套锚定词——**两张表不闭合**。
 * 于是「码明明抽得出来、却进不了门」的写法整条无痕蒸发：不落库、不进未识别、组件角标也不出现，
 * 用户永远不会在任何地方看到少了他一件。语料里已经坐实两条：
 * 极兔「请凭6-99-226到极兔领取」、兔喜「已入库…请凭数字密码 8-9-0765 到柜领取」。
 *
 * 现在的顺序是刻意的，两条优先关系都不能换：
 *
 * 1. **强锚定优先于负向锚。** 真实取件短信会写「取件码 8-3-7713，请勿泄露给他人」，
 *    验证码短信写「验证码 610920，请勿泄露」——两者唯一的区别就是那个锚定词。
 *    所以锚定词一命中，负向锚就没有否决权。
 * 2. **弱锚定必须有语境。** 「请使用 889900 完成支付」也抽得出数字，但它不是取件。
 */
object MessageGate {

    /**
     * 负向锚：一看就不是取件消息的词。
     * 「请勿泄露」在这里，靠上面第 1 条的优先关系才不会误伤真实取件码。
     */
    private val NOT_PICKUP = Regex(
        "验证码|校验码|动态密码|请勿泄露|优惠券|补贴|折扣|退订|中奖|积分|流量包"
    )

    /**
     * 取件语境。窄到「只有取件才会这么写」为止——宽一条，就多一条挤进未识别列表的垃圾，
     * 而角标一旦常年是个无意义的数字，用户会直接忽略它，整套「失败显性化」就废了。
     */
    private val PICKUP_CONTEXT = Regex(
        "取件|提货|取货|领取|入库|入柜|已放入|已投递|投递到|投递至|到站|" +
            "快递柜|智能柜|柜|驿站|代收|收发室|自提|货架|支局|门店|" +
            "丰巢|菜鸟|兔喜|近邻宝|速递易|袋鼠"
    )

    /**
     * 这条消息允许带着码进门吗？
     *
     * @param strong 码是不是由**本身就带取件语义**的锚定词抽出来的（「取件码」「领取码」…）。
     */
    fun admitsCode(body: String, strong: Boolean): Boolean = strong || looksLikePickup(body)

    /** 正文本身是不是在喊人去取件——不含任何码也算，那是「该给个原因」而不是「该丢掉」。 */
    fun looksLikePickup(body: String): Boolean =
        !NOT_PICKUP.containsMatchIn(body) && PICKUP_CONTEXT.containsMatchIn(body)

    /**
     * 用户自己写的规则命中之后，这条消息允不允许成卡。
     *
     * 这里**不看负向锚**：规则本身就是用户为某个写法写死的锚定词，比内置词表更强。
     * 但语境仍然要看，而且不能松——写「(\d{6})」这种宽规则的人，会直接把验证码短信
     * 收成一张标着「楼下驿站」的假卡。误收一张的代价远大于漏收一条：
     * 用户是站在柜机前发现假的。
     */
    fun admitsRuleHit(body: String): Boolean = PICKUP_CONTEXT.containsMatchIn(body)
}
